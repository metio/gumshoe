(ns gumshoe.progress-transcript-support
  "A fixed scenario of task lists and the byte output it gives off a
   terminal and under --no-color, kept as a golden transcript so the plain
   output of a list is pinned byte for byte."
  (:require [clojure.edn :as edn]
            [clojure.java.io :as io]
            [clojure.pprint :as pprint]
            [clojure.string :as str]
            [gumshoe.progress :as progress]
            [gumshoe.stdout :as stdout]))

(def golden-path "tests/golden/progress_plain.edn")

(defn scenario!
  "Every kind of row and text a plain list prints, each once, in an order
   that does not depend on timing."
  []
  (progress/run-steps
   [{:label "reads pods" :run #(do (stdout/ok "3 pods") (stdout/note "all ready") true)}
    {:label "fails" :run (constantly false)}
    {:label "throws" :run #(throw (ex-info "boom" {}))}
    {:label "unread" :run #(throw (ex-info "no answer" {:gumshoe.kubectl/unread true}))}
    {:label "skipped" :run (constantly {:skipped? true})}
    {:label "relabelled" :run (constantly {:ok? true :label "relabelled (v1.36)"})}
    {:label "with a reason" :run (constantly {:ok? false :reason "the claim is pending"})}
    {:label "waits" :run #(do (progress/status! "12 of 48 reads") true)}
    {:label "nested" :run #(progress/checklist [["inner one" (constantly true)]
                                                ["inner two" (constantly false)]]
                                               {:stop-on-failure? false})}
    {:label "parallel inside" :run #(do (progress/watch-futures! [["pods" (future 1)] ["events" (future 2)]]) true)}
    {:label "prints to stderr" :run #(do (binding [*out* *err*] (println "2 nodes")) true)}]
   {:stop-on-failure? false})
  (progress/with-board [b]
    (let [one (progress/add! b "first")
          two (progress/add! b "second")
          _ (progress/add! b "never started")]
      (binding [*out* *err*] (println "loose text outside any step"))
      (progress/start! b two)
      (progress/settle! b two {:ok? true :label "second (3 of 3)"})
      (progress/run! b one (constantly true))
      (progress/run! b "added late" (constantly false))))
  (progress/run-steps [{:label "stops" :run (constantly false)}
                       {:label "never runs" :run (constantly true)}])
  (progress/watch-futures! [["alone" (future :a)] ["together" (future :b)]])
  nil)

(defn- capture
  "What scenario! writes to stderr and stdout with stderr a terminal or not
   and the --no-color flag set or not; colour on for every other printer
   unless the flag turned it off."
  [{:keys [stderr-terminal? no-color-flag?]}]
  (let [flag @#'stdout/no-color-flag?
        colors @#'stdout/colors?
        before [@flag @colors]
        err (java.io.StringWriter.)
        out (java.io.StringWriter.)]
    (try
      (reset! flag false)
      (reset! colors true)
      (when no-color-flag? (stdout/disable-colors!))
      (with-redefs-fn {#'progress/terminal? (fn [fd] (and stderr-terminal? (= 2 fd)))}
        #(binding [*err* err *out* out stdout/*width* 80] (scenario!)))
      (finally
        (reset! flag (first before))
        (reset! colors (second before))))
    {:err (str err) :out (str out)}))

(defn transcripts
  "The scenario's output in each plain setting."
  []
  {:redirected (capture {:stderr-terminal? false})
   :no-color-flag (capture {:stderr-terminal? true :no-color-flag? true})})

(defn golden
  []
  (edn/read-string (slurp golden-path)))

(defn write-golden!
  "Rewrites the golden transcript from the code as it is now."
  []
  (with-open [w (io/writer golden-path)]
    (.write w ";; SPDX-FileCopyrightText: The gumshoe Authors\n;; SPDX-License-Identifier: 0BSD\n;;\n;; Generated by (gumshoe.progress-transcript-support/write-golden!); review its diff.\n")
    ;; the escape character written as \\u001b, so the file stays printable text
    (.write w (str/replace (with-out-str (pprint/pprint (transcripts))) "\u001b" "\\u001b"))))
