(ns gumshoe.book-surfaces-test
  "Characterises the command line of every book gumshoe ships: the options
   the harness parses its arguments with, the --help text it prints, and
   what a set of probe arguments parses to. Each book is loaded with
   runbook/*loading* bound, so the harness hands back its config and runs
   nothing.

   The probes cover the flags whose short alias the select convention
   decides, so a change to an alias shows up here as a changed parse rather
   than only as a changed option map.

   The surfaces are kept in tests/golden/book_surfaces.edn. Regenerate the
   file after an intended change with (gumshoe.book-surfaces-test/write-golden!)
   under NO_COLOR=1 and review its diff."
  (:require [babashka.fs :as fs]
            [clojure.edn :as edn]
            [clojure.pprint :as pprint]
            [clojure.string :as str]
            [clojure.test :refer [deftest is testing]]
            [clojure.walk :as walk]
            [gumshoe.runbook :as runbook]
            [gumshoe.stdout :as stdout]))

(def golden-path "tests/golden/book_surfaces.edn")

(def ^:private book-dirs #{"runbooks" "playbooks" "firebooks"})

(defn book-files
  "Every book under the core roots and the tool packages, sorted."
  []
  (vec (sort (for [root (concat book-dirs
                                (for [tool (fs/list-dir "tools")
                                      dir (fs/list-dir tool)
                                      :when (and (fs/directory? dir) (book-dirs (str (fs/file-name dir))))]
                                  (str dir)))
                   :when (fs/directory? root)
                   file (fs/glob root "**.clj")]
               (str file)))))

(defn- load-config
  [path]
  (binding [runbook/*loading* true]
    (load-file path)))

(defn- normalise
  "Functions print by their class, which changes with every load."
  [x]
  (walk/postwalk #(if (fn? %) :fn %) x))

(def ^:private probe-values
  "The values a probe passes, by the option it names."
  {:name "web" :service "query" :namespace "shop"})

(defn probes
  "The argument lists a book is probed with: each short alias in use today
   or by the convention, and the long flag, for every probed option it has."
  [options]
  (vec (for [[option letters] [[:name ["-N" "-r" "-s"]]
                               [:service ["-m" "-s"]]]
             :when (contains? options option)
             flag (concat letters [(str "--" (name option))])]
         [flag (probe-values option)])))

(defn- parse
  [options argv]
  (try
    (runbook/arguments options argv)
    (catch Exception e (str "threw: " (ex-message e)))))

(defn- help-lines
  "The --help text as lines. Its usage line names the script bb runs, which
   is this harness's caller rather than the book, so it reads as the book's
   own placeholder."
  [config]
  (mapv #(str/replace % #"^  bb .* \[options\]$" "  bb <runbook> [options]")
        (str/split-lines (stdout/strip-colors (runbook/help config)))))

(defn surface
  [config]
  (let [options (or (:options config) {})]
    (normalise
     (cond-> {:options (into (sorted-map) options)
              :help (help-lines config)}
       (seq (probes options))
       (assoc :parsed (into (sorted-map)
                            (for [argv (probes options)]
                              [(str/join " " argv) (parse options argv)])))))))

(defn surfaces
  []
  (into (sorted-map)
        (for [path (book-files)]
          [path (surface (load-config path))])))

(defn write-golden!
  []
  (spit golden-path
        ;; split, so a REUSE scan does not read these strings as this file's header
        (str ";; SPDX" "-FileCopyrightText: The gumshoe Authors\n"
             ";; SPDX" "-License-Identifier: 0BSD\n"
             ";; Generated by (gumshoe.book-surfaces-test/write-golden!); review its diff.\n"
             (with-out-str (pprint/pprint (surfaces))))))

(deftest every-book-keeps-its-surface
  (let [golden (edn/read-string (slurp golden-path))
        actual (surfaces)]
    (is (= (set (keys golden)) (set (keys actual))) "the same books")
    (doseq [[path surface] actual]
      (testing path
        (is (= (get golden path) surface))))))
